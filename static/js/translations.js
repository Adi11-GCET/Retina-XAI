window.translations = translations;

let currentLang = localStorage.getItem('retina_lang') || 'en';

function setLanguage(lang) {
  if (!translations[lang]) {
    lang = 'en';
  }
  currentLang = lang;
  localStorage.setItem('retina_lang', lang);

  // Update all lang buttons in UI
  document.querySelectorAll('.lang-btn').forEach(btn => {
    if (btn.dataset.lang === lang) {
      btn.classList.add('active');
      btn.setAttribute('aria-pressed', 'true');
    } else {
      btn.classList.remove('active');
      btn.setAttribute('aria-pressed', 'false');
    }
  });

  // Translate text elements with data-i18n
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (translations[lang] && translations[lang][key]) {
      el.textContent = translations[lang][key];
    } else if (translations['en'] && translations['en'][key]) {
      el.textContent = translations['en'][key];
    }
  });

  // Translate placeholders with data-i18n-ph
  document.querySelectorAll('[data-i18n-ph]').forEach(el => {
    const key = el.getAttribute('data-i18n-ph');
    if (translations[lang] && translations[lang][key]) {
      el.setAttribute('placeholder', translations[lang][key]);
    } else if (translations['en'] && translations['en'][key]) {
      el.setAttribute('placeholder', translations['en'][key]);
    }
  });

  // Translate title/aria-labels with data-i18n-title
  document.querySelectorAll('[data-i18n-title]').forEach(el => {
    const key = el.getAttribute('data-i18n-title');
    if (translations[lang] && translations[lang][key]) {
      el.setAttribute('title', translations[lang][key]);
      el.setAttribute('aria-label', translations[lang][key]);
    } else if (translations['en'] && translations['en'][key]) {
      el.setAttribute('title', translations['en'][key]);
      el.setAttribute('aria-label', translations['en'][key]);
    }
  });

  // Synchronize Voice modal language select if present
  const voiceSelect = document.getElementById('voiceModalLangSelect');
  if (voiceSelect) {
    voiceSelect.value = lang;
  }

  // Broadcast event for dynamic components (charts, chatbot, voice)
  window.dispatchEvent(new CustomEvent('languageChanged', { detail: { lang } }));
}

window.setLanguage = setLanguage;
window.getCurrentLanguage = () => currentLang;

document.addEventListener('DOMContentLoaded', () => {
  setLanguage(currentLang);

  document.querySelectorAll('.lang-btn').forEach(btn => {
    btn.addEventListener('click', (e) => {
      const selected = e.currentTarget.dataset.lang;
      setLanguage(selected);
    });
  });
});
